package jp.kamusoft.ksdialogs.kmp

/**
 * ダイアログを基準領域のどこへ寄せるか。
 *
 * [START] / [END] は物理方向 (水平軸なら左 / 右、垂直軸なら上 / 下) を指し、書字方向 (RTL) には追随しない。
 * 意味は各 OS の Native ライブラリの同名の型と同一で、共有コードで指定した値は無変換で届く (core/ADR-0001)。
 */
public enum class DialogAlignment {
    /** 有効領域の前端 (左 / 上) に寄せる。 */
    START,

    /** 有効領域の中央に置く。 */
    CENTER,

    /** 有効領域の後端 (右 / 下) に寄せる。 */
    END,

    /**
     * 位置だけでなくサイズも有効領域いっぱいに広げる。
     *
     * 比率サイズが指定されている軸ではサイズの決め方として採用されず、位置は [CENTER] として扱う。
     */
    FILL,
}
